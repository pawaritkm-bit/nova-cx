-- =====================================================================
-- 0060 — เพิ่มคอลัมน์ "เดือนที่ใช้ภาษีซื้อ" (bill_entries.input_tax_month)
-- =====================================================================
-- บริบท (บัญชี):
--   ภาษีซื้อ (input VAT) ตามกฎหมายไทย ใช้เครดิตในเดือนที่ลงบิล หรือ "ยกไปใช้
--   เดือนถัด ๆ" ได้ (ภายใน 6 เดือน). บิลซื้อแต่ละใบจึงมี "เดือนที่ใช้ภาษี" ที่
--   อาจต่างจากวันที่บิล และรายงานภาษีซื้อต้องยึด "เดือนที่ใช้ภาษี" ไม่ใช่วันที่บิล.
--
--   * รูปแบบค่า = 'YYYY-MM' (ค.ศ.) เช่น '2026-07'
--   * null (ค่าโดยปริยาย) = ใช้เดือนของ doc_date (พฤติกรรมเดิม — ไม่ยกเดือน)
--   * ใช้เฉพาะบิลซื้อ (entry_type='purchase') — บิลขาย/รอระบุ ไม่ใช้คอลัมน์นี้
--   * non-destructive: add column if not exists (ปลอดภัยต่อข้อมูลเดิม)
--   * ยังไม่มี RLS ใหม่ — ใช้ policy เดิมของตาราง bill_entries
-- =====================================================================

alter table public.bill_entries
  add column if not exists input_tax_month text;

-- reload schema cache ของ PostgREST (กัน 500 "column not found in schema cache"
--   หลัง apply — ดูบทเรียนทีม supabase-schema-cache-reload)
notify pgrst, 'reload schema';
