/**
 * อัตราภาษีหัก ณ ที่จ่าย (WHT) แนะนำตาม "ประเภทบัญชีค่าใช้จ่าย" + เลือกแบบยื่น ภงด.3/53
 *   ★ เป็นเพียง "ค่าแนะนำ" ให้ช่องหัก ณ ที่จ่ายในหน้าลงบันทึกบัญชี — ไม่ล็อก · นักบัญชีแก้ได้เสมอ
 *   ★ ถ้า AI อ่านอัตรา/ยอดหักจากบิลได้จริง (high-confidence) worker ใช้ค่านั้นก่อน · ตารางนี้ใช้เมื่อบิลไม่แสดง WHT
 *
 * อ้างอิงกฎหมาย: ประมวลรัษฎากร มาตรา 3 เตรส + คำสั่งกรมสรรพากร ท.ป.4/2528 (และที่แก้ไขเพิ่มเติม)
 *   - ค่าขนส่ง (ไม่รวมขนส่งสาธารณะ)                = 1%
 *   - ค่าโฆษณา                                     = 2%
 *   - ค่าบริการ/ค่าจ้างทำของ/รับเหมา/ซ่อม/ธรรมเนียม = 3%
 *   - ค่าวิชาชีพอิสระ (กฎหมาย/บัญชี/วิศวะ/สถาปัตย์/แพทย์/ประณีตศิลป์) = 3%
 *   - ค่าเช่าทรัพย์สิน                              = 5%
 *   - ดอกเบี้ยจ่าย (จ่ายให้นิติบุคคล)              = 1%
 *   ★ หมายเหตุ: อัตราลดชั่วคราวตาม พรฎ. (เช่น e-Withholding 1-2%) ใช้เฉพาะ "หัก ณ ที่จ่ายผ่านระบบ
 *     อิเล็กทรอนิกส์ (e-WHT)" เท่านั้น — ระบบนี้ออกแบบยื่นกระดาษ ภงด.3/53 จึงใช้ "อัตรามาตรฐาน" ข้างต้น
 *     (ถ้าจะรองรับ e-WHT ในอนาคต ค่อยเพิ่ม effective dating ต่อรหัสบัญชี)
 */

/** รหัสบัญชี (จากผังกลาง) → อัตรา WHT % ที่แนะนำ */
export const WHT_RATE_BY_ACCOUNT: Readonly<Record<string, number>> = {
  // ค่าขนส่ง = 1% (ท.ป.4/2528 ข้อ 12/1)
  "5341": 1, // ค่าขนส่ง
  "5337": 1, // ค่าบริการค่าขนส่ง
  "5010.3": 1, // ค่าขนส่งเมื่อซื้อ
  // ดอกเบี้ยจ่าย (ให้นิติบุคคล) = 1% (ท.ป.4/2528 ข้อ 4)
  "5360": 1, // ดอกเบี้ยจ่าย
  // ค่าโฆษณา = 2% (ท.ป.4/2528 ข้อ 10)
  "5315": 2, // ค่าโฆษณา
  // ค่าบริการ/ค่าจ้างทำของ/ค่าซ่อม/ค่าธรรมเนียม/วิชาชีพ = 3% (ท.ป.4/2528 ข้อ 8, 12; ม.3 เตรส)
  "5342": 3, // ค่าบริการ
  "5343": 3, // ค่าบริการเครื่องถ่ายเอกสาร
  "5344": 3, // ค่าบริการแพลตฟอร์ม
  "5345": 3, // ค่าบำรุงรักษายานพาหนะ
  "5347": 3, // ค่าธรรมเนียมวิชาชีพ (เพิ่ม migration 0119)
  "5352": 3, // ค่าซ่อมแซม
  "5355": 3, // ค่าธรรมเนียมอื่น ๆ
  // ค่าเช่าทรัพย์สิน = 5% (ท.ป.4/2528 ข้อ 6; ม.3 เตรส)
  "5346": 5, // ค่าเช่า (เพิ่ม migration 0119)
};

/**
 * แนะนำอัตรา WHT % จากรหัสบัญชี (pure) — ไม่รู้จัก/null = 0 (ไม่หัก, ไม่เดา)
 */
export function suggestWhtRate(accountCode: string | null | undefined): number {
  if (!accountCode) return 0;
  return WHT_RATE_BY_ACCOUNT[accountCode.trim()] ?? 0;
}

/** แบบยื่นหัก ณ ที่จ่าย: pnd3 = ผู้รับเงินเป็นบุคคลธรรมดา · pnd53 = นิติบุคคล */
export type WhtForm = "pnd3" | "pnd53" | null;

/**
 * เดาแบบยื่น (ภงด.3/53) จาก "ผู้ถูกหัก" (= ผู้รับเงิน/คู่ค้า) — pure
 *   ★ เกณฑ์เลขประจำตัวผู้เสียภาษี 13 หลัก: ขึ้นต้น '0' = นิติบุคคล (เลขทะเบียนนิติบุคคล) → ภงด.53
 *     ขึ้นต้น 1-8 = เลขบัตร ปชช บุคคลธรรมดา → ภงด.3  (กรมพัฒน์ฯ/สรรพากร)
 *   ★ ถ้าระบุ counterpartyType มา (จาก customers.customer_type) ใช้ก่อน (แม่นกว่าเดาเลข)
 *   ไม่มีข้อมูล → null (ให้นักบัญชีเลือกเอง ไม่เดามั่ว)
 */
export function suggestWhtForm(
  counterpartyTaxId: string | null | undefined,
  counterpartyType?: "company" | "individual" | null
): WhtForm {
  if (counterpartyType === "company") return "pnd53";
  if (counterpartyType === "individual") return "pnd3";
  const digits = (counterpartyTaxId ?? "").replace(/\D/g, "");
  if (digits.length === 13) return digits.startsWith("0") ? "pnd53" : "pnd3";
  return null;
}
