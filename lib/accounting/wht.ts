/**
 * อัตราภาษีหัก ณ ที่จ่าย (WHT) แนะนำตาม "ประเภทบัญชีค่าใช้จ่าย"
 *   ★ เป็นเพียง "ค่าแนะนำ" ให้ช่องหัก ณ ที่จ่ายในหน้าลงบันทึกบัญชี — ไม่ล็อก
 *     นักบัญชีแก้ได้เสมอ (บางเคสผู้รับเงินเป็นบุคคล/นิติบุคคล/ยกเว้น อัตราต่างกัน)
 *   ★ จับเฉพาะบัญชีที่ "อัตรามาตรฐานชัดเจน" เท่านั้น — บัญชีที่เหลือคืน 0 (ไม่เดา)
 *   ★ ถ้า AI อ่านอัตรา/ยอดหักจากบิลได้จริง (high-confidence) worker จะใช้ค่านั้นก่อน
 *     ค่าจากตารางนี้ใช้ต่อเมื่อบิลไม่ได้แสดง WHT ไว้
 *
 * อ้างอิงประมวลรัษฎากร (มาตรา 3 เตรส / ท.ป.4/2528) อัตราที่พบบ่อย:
 *   - ค่าขนส่ง = 1%
 *   - ค่าโฆษณา = 2%
 *   - ค่าบริการ/ค่าจ้างทำของ/ค่าซ่อม/ค่าธรรมเนียม = 3%
 *   (ค่าเช่า = 5% — ผังบัญชีกลางยังไม่มีรหัส "ค่าเช่า" จึงไม่แม็ป)
 */

/** รหัสบัญชี (จากผังกลาง) → อัตรา WHT % ที่แนะนำ */
export const WHT_RATE_BY_ACCOUNT: Readonly<Record<string, number>> = {
  // ค่าขนส่ง = 1%
  "5341": 1, // ค่าขนส่ง
  "5337": 1, // ค่าบริการค่าขนส่ง
  "5010.3": 1, // ค่าขนส่งเมื่อซื้อ
  // ค่าโฆษณา = 2%
  "5315": 2, // ค่าโฆษณา
  // ค่าบริการ/ค่าจ้าง/ค่าซ่อม/ค่าธรรมเนียม = 3%
  "5342": 3, // ค่าบริการ
  "5343": 3, // ค่าบริการเครื่องถ่ายเอกสาร
  "5344": 3, // ค่าบริการแพลตฟอร์ม
  "5345": 3, // ค่าบำรุงรักษายานพาหนะ
  "5352": 3, // ค่าซ่อมแซม
  "5355": 3, // ค่าธรรมเนียมอื่น ๆ
};

/**
 * แนะนำอัตรา WHT % จากรหัสบัญชี (pure) — ไม่รู้จัก/null = 0 (ไม่หัก, ไม่เดา)
 *   คืนค่าเป็น "อัตราแนะนำ" ให้ worker/UI เติมช่องหัก ณ ที่จ่าย (นักบัญชีแก้ได้)
 */
export function suggestWhtRate(accountCode: string | null | undefined): number {
  if (!accountCode) return 0;
  return WHT_RATE_BY_ACCOUNT[accountCode.trim()] ?? 0;
}
